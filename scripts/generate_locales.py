"""Generate all platform catalogs from localization/locales and shared/catalog/themes.json.

Run with --check in CI to reject incomplete translations or stale generated resources.
Uses only Python's standard library; translations are reviewed source files, never API calls.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
PLACEHOLDER = re.compile(r'%(?:\d+\$)?[sdif]|%%')


def read(path):
    return json.loads((ROOT / path).read_text(encoding='utf-8'))


def validate_messages(english, messages, language):
    missing = english.keys() - messages.keys()
    extra = messages.keys() - english.keys()
    if missing or extra:
        raise ValueError(f'{language}: missing {sorted(missing)}, extra {sorted(extra)}')
    for key, original in english.items():
        value = messages[key]
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f'{language}/{key}: empty translation')
        if Counter(PLACEHOLDER.findall(original)) != Counter(PLACEHOLDER.findall(value)):
            raise ValueError(f'{language}/{key}: placeholder mismatch')
        if original.count('\n') != value.count('\n'):
            raise ValueError(f'{language}/{key}: newline mismatch')
        if '\ufffd' in value or re.search(r'\?{3,}', value):
            raise ValueError(f'{language}/{key}: damaged Unicode')


def android_xml(messages, keys):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/generate_locales.py. Edit localization/locales instead. -->', '<resources>']
    for key in keys:
        value = messages[key].replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r')
        lines.append(f'    <string name="{key}">{escape(value)}</string>')
    return '\n'.join(lines + ['</resources>', ''])


def contrast(a, b):
    def luminance(color):
        rgb = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
        return sum(w * (v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4) for w, v in zip((.2126, .7152, .0722), rgb))
    x, y = sorted((luminance(a), luminance(b)))
    return (y + .05) / (x + .05)


def outputs():
    languages = read('localization/languages.json')
    english = read('localization/locales/en.json')
    messages = {}
    for language in languages:
        code = language['code']
        messages[code] = read(f'localization/locales/{code}.json')
        validate_messages(english, messages[code], code)
    themes = read('shared/catalog/themes.json')
    if len({t['id'] for t in themes}) != len(themes):
        raise ValueError('Duplicate theme ID')
    for theme in themes:
        for mode in ('light', 'dark'):
            colors = theme[mode]
            for value in colors.values():
                if not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
                    raise ValueError(f'Invalid color {value}')
            for surface in ('background', 'panel'):
                for ink in ('foreground', 'muted', 'accent'):
                    if contrast(colors[ink], colors[surface]) < 4.5:
                        raise ValueError(f'Insufficient contrast: {theme["id"]}/{mode}/{ink}')
            for surface in ('gradientStart', 'gradientEnd'):
                for ink in ('foreground', 'muted'):
                    if contrast(colors[ink], colors[surface]) < 4.5:
                        raise ValueError(f'Insufficient gradient contrast: {theme["id"]}/{mode}/{ink}')
    catalog = dict(languages=languages, messages=messages, themes=themes,
                   desktopKeys=read('localization/desktop-keys.json'),
                   englishKeys={value: key for key, value in english.items()})
    payload = json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))
    generated = {}
    android_keys = read('localization/android-keys.json')
    for language in languages:
        generated[ROOT / f'android/src/main/res/{language["android"]}/strings.xml'] = android_xml(messages[language['code']], android_keys)
    generated[ROOT / 'ios/TorikomiCore/Resources/catalog.json'] = payload + '\n'
    generated[ROOT / 'shared/desktop/ui/catalog.js'] = '''// Generated by scripts/generate_locales.py. Edit localization/ and shared/catalog/ instead.
const TorikomiCatalog = ''' + payload + ''';
TorikomiCatalog.resolveLanguage = function(raw, system = 'en') {
  const value = String(raw === 'system' ? system : raw || 'en').replaceAll('_','-').toLowerCase();
  if (value === 'in' || value.startsWith('in-')) return 'id';
  if (value.startsWith('zh')) return /(?:hant|tw|hk|mo)/.test(value) ? 'zh-TW' : 'zh-CN';
  return this.languages.find(l => l.code.toLowerCase() === value)?.code || this.languages.find(l => l.code === value.split('-')[0])?.code || 'en';
};
TorikomiCatalog.theme = function(id) { return this.themes.find(t => t.id === id) || this.themes.find(t => t.id === 'violet'); };
TorikomiCatalog.text = function(key, language) { const id = this.desktopKeys[key] || key; return this.messages[this.resolveLanguage(language)]?.[id] || this.messages.en[id] || key; };
if (typeof module !== 'undefined') module.exports = TorikomiCatalog;
'''
    kotlin = ['// Generated by scripts/generate_locales.py.', 'package univzy.torikomi.data.model', '',
              'data class AppLanguage(val code: String, val name: String, val rtl: Boolean)',
              'data class ThemeColors(val background: Long, val panel: Long, val foreground: Long, val muted: Long, val border: Long, val accent: Long, val gradientStart: Long, val gradientEnd: Long)',
              'data class ThemePreset(val id: String, val name: String, val group: String, val mode: String, val swatch: List<Long>, val light: ThemeColors, val dark: ThemeColors)',
              'object AppCatalog {', '    val languages = listOf(']
    for language in languages:
        kotlin.append(f'        AppLanguage("{language["code"]}", "{language["name"]}", {str(language["rtl"]).lower()}),')
    kotlin.extend(['    )', '    val themes = listOf('])
    def color(value): return '0xFF' + value[1:].upper()
    for theme in themes:
        pairs = ', '.join('ThemeColors(' + ', '.join(color(theme[mode][key]) for key in ('background', 'panel', 'foreground', 'muted', 'border', 'accent', 'gradientStart', 'gradientEnd')) + ')' for mode in ('light', 'dark'))
        kotlin.append(f'        ThemePreset("{theme["id"]}", "{theme["name"]}", "{theme["group"]}", "{theme["mode"]}", listOf({", ".join(map(color, theme["swatch"]))}), {pairs}),')
    kotlin.extend(['    )', '    val themeIds = themes.map { it.id }.toSet()', '    fun theme(id: String) = themes.firstOrNull { it.id == id } ?: themes.first { it.id == "violet" }', '}', ''])
    generated[ROOT / 'android/src/main/java/univzy/torikomi/data/model/AppCatalog.kt'] = '\n'.join(kotlin)
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check completeness and stale output without writing')
    args = parser.parse_args()
    try:
        generated = outputs()
        stale = []
        for path, content in generated.items():
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
                if not args.check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    temporary = path.with_suffix(path.suffix + '.tmp')
                    temporary.write_text(content, encoding='utf-8', newline='\n')
                    temporary.replace(path)
        if args.check and stale:
            raise ValueError('Stale generated files: ' + ', '.join(stale))
        print(f'{len(generated)} platform resources {"checked" if args.check else "generated"}; {len(read("localization/languages.json"))} languages.')
        return 0
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
